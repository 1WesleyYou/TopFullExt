#!/usr/bin/env bash
set -euo pipefail

# Base load + timed network fault injection + runtime steering mitigation.
#
# Timeline:
#   (caller starts desired stack: make start / make rl / make mimd / etc.)
#   t=0                              base load starts
#   t=BASE_SETTLE                    netem injected (packet loss) → valley
#   t=BASE_SETTLE + STEER_DELAY      steering monitor starts → detect + redirect
#   t=BASE_SETTLE + FAULT_SEC        netem cleared + steering stopped + pods restored
#   t=... + TAIL_SEC                 experiment ends
#
# All knobs (override via env):
#   BASE_RATE       load rate %                      (default 30)
#   NET_DELAY_MS    added latency ms                 (default 0)
#   NET_LOSS_PCT    packet loss %                    (default 70)
#   NET_DIRECTION   egress | ingress | both          (default egress)
#   BASE_SETTLE     warmup seconds before fault      (default 90)
#   FAULT_SEC       fault duration seconds            (default 140)
#   TAIL_SEC        post-fault observation seconds    (default 90)
#   POD_COUNT       inject into first N matched pods  (default 3)
#   STEER_DELAY     seconds after fault before steering starts (default 30)
#   STEERING_INTERVAL  steering monitor poll interval (default 5)
#   PHASE_LOG       path for phase_markers file
#
# Usage:
#   ./run_steering_experiment.sh
#   BASE_RATE=30 POD_COUNT=3 NET_LOSS_PCT=70 STEER_DELAY=30 ./run_steering_experiment.sh

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

BASE_RATE="${BASE_RATE:-30}"
SURGE_RATE="${SURGE_RATE:-0}"
NET_DELAY_MS="${NET_DELAY_MS:-0}"
NET_LOSS_PCT="${NET_LOSS_PCT:-70}"
NET_DIRECTION="${NET_DIRECTION:-egress}"
BASE_SETTLE="${BASE_SETTLE:-90}"
FAULT_SEC="${FAULT_SEC:-140}"
TAIL_SEC="${TAIL_SEC:-90}"
POD_COUNT="${POD_COUNT:-3}"
STEER_DELAY="${STEER_DELAY:-30}"
STEERING_INTERVAL="${STEERING_INTERVAL:-5}"
PHASE_LOG="${PHASE_LOG:-${SCRIPT_DIR}/phase_markers_steering.env}"
NETEM_CLEARED=0
STEERING_PID=""

# Propagate subset knob to net_delay_k8s.sh.
export NET_TARGET_POD_COUNT="${POD_COUNT}"

TOTAL=$(( BASE_SETTLE + FAULT_SEC + TAIL_SEC ))
REMAINING_FAULT=$(( FAULT_SEC - STEER_DELAY ))

ts() { printf "[%s]" "$(date +'%H:%M:%S')"; }

append_phase_ts() {
  local key="$1" iso epoch
  iso="$(date -Iseconds)"; epoch="$(date -u +%s)"
  printf "%s_ISO=%s\n%s_EPOCH=%s\n" "${key}" "${iso}" "${key}" "${epoch}" >> "${PHASE_LOG}"
}

cleanup() {
  echo "$(ts) Cleanup: clearing netem + stopping steering + restoring pods..."
  if [[ "${NETEM_CLEARED}" != "1" ]]; then
    bash "${SCRIPT_DIR}/net_delay_k8s.sh" clear 2>/dev/null || true
  fi
  if [[ -n "${STEERING_PID}" ]]; then
    kill "${STEERING_PID}" 2>/dev/null || true
    wait "${STEERING_PID}" 2>/dev/null || true
  fi
  bash "${SCRIPT_DIR}/pod_health_steering.sh" restore 2>/dev/null || true
}
trap cleanup EXIT INT TERM

# ---- Header ----
echo "$(ts) === Steering Experiment ==="
echo "$(ts) BASE_RATE=${BASE_RATE}%  NET_LOSS_PCT=${NET_LOSS_PCT}%  NET_DIRECTION=${NET_DIRECTION}  POD_COUNT=${POD_COUNT}"
echo "$(ts) STEER_DELAY=${STEER_DELAY}s  STEERING_INTERVAL=${STEERING_INTERVAL}s"
echo "$(ts) Timeline: base ${BASE_SETTLE}s -> fault ${FAULT_SEC}s (steer at +${STEER_DELAY}s) -> tail ${TAIL_SEC}s (total ${TOTAL}s)"
echo ""

cat > "${PHASE_LOG}" <<EOF
# Generated by run_steering_experiment.sh
BASE_RATE=${BASE_RATE}
SURGE_RATE=${SURGE_RATE}
NET_DELAY_MS=${NET_DELAY_MS}
NET_LOSS_PCT=${NET_LOSS_PCT}
NET_DIRECTION=${NET_DIRECTION}
BASE_SETTLE=${BASE_SETTLE}
FAULT_SEC=${FAULT_SEC}
TAIL_SEC=${TAIL_SEC}
POD_COUNT=${POD_COUNT}
STEER_DELAY=${STEER_DELAY}
STEERING_INTERVAL=${STEERING_INTERVAL}
EOF

# ---- Step 0: pre-clear ----
echo "$(ts) Step 0: pre-clear netem + restore any steered pods"
bash "${SCRIPT_DIR}/net_delay_k8s.sh" clear || true
bash "${SCRIPT_DIR}/pod_health_steering.sh" restore 2>/dev/null || true

# ---- Step 1: base load ----
echo "$(ts) Step 1: start base load RATE=${BASE_RATE}%"
append_phase_ts "BASE_LOAD_START"
make -C "${SCRIPT_DIR}" inject-base "RATE=${BASE_RATE}"

# ---- Step 2: wait then inject fault ----
echo "$(ts) Step 2: waiting ${BASE_SETTLE}s before fault injection..."
sleep "${BASE_SETTLE}"
append_phase_ts "NET_DELAY_START"

if [[ "${NET_DELAY_MS}" == "0" && "${NET_LOSS_PCT}" == "0" ]]; then
  echo "$(ts) Step 2: delay=0 and loss=0 -> skipping netem"
else
  export NET_DELAY_MS NET_LOSS_PCT NET_DIRECTION
  bash "${SCRIPT_DIR}/net_delay_k8s.sh" set
  bash "${SCRIPT_DIR}/net_delay_k8s.sh" status || true
fi

# ---- Step 3: wait STEER_DELAY (let valley develop) ----
echo "$(ts) Step 3: fault active, waiting ${STEER_DELAY}s before starting steering..."
sleep "${STEER_DELAY}"

# ---- Step 4: start steering monitor ----
append_phase_ts "STEERING_START"
echo "$(ts) Step 4: starting steering monitor (interval=${STEERING_INTERVAL}s)"
STEERING_INTERVAL="${STEERING_INTERVAL}" \
  bash "${SCRIPT_DIR}/pod_health_steering.sh" monitor > >(while IFS= read -r line; do echo "  [steering] ${line}"; done) 2>&1 &
STEERING_PID=$!

# ---- Step 5: wait remaining fault duration ----
echo "$(ts) Step 5: steering active, fault continues for ${REMAINING_FAULT}s..."
sleep "${REMAINING_FAULT}"

# ---- Step 6: clear fault + stop steering ----
append_phase_ts "NET_DELAY_END"
echo "$(ts) Step 6: clearing netem"
bash "${SCRIPT_DIR}/net_delay_k8s.sh" clear
NETEM_CLEARED=1

echo "$(ts) Step 6b: stopping steering monitor"
kill "${STEERING_PID}" 2>/dev/null || true
wait "${STEERING_PID}" 2>/dev/null || true
STEERING_PID=""
append_phase_ts "STEERING_END"

echo "$(ts) Step 6c: restoring all steered pods"
bash "${SCRIPT_DIR}/pod_health_steering.sh" restore

# ---- Step 7: tail observation ----
echo "$(ts) Step 7: post-fault tail ${TAIL_SEC}s"
append_phase_ts "TAIL_START"
sleep "${TAIL_SEC}"

append_phase_ts "EXPERIMENT_END"
echo "$(ts) Done."
