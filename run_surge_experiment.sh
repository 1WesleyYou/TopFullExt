#!/usr/bin/env bash
set -euo pipefail

# Base → Surge → Base tail → Stop
#
# Timeline (defaults):
#   0:00  base load starts
#   1:00  surge overlay begins (base continues)
#   1:40  surge ends automatically (-t flag)
#   3:40  experiment complete, all load stopped
#
# Usage:
#   ./run_surge_experiment.sh
#   BASE_SETTLE=90 SURGE_SEC=60 TAIL_SEC=180 ./run_surge_experiment.sh

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="${SCRIPT_DIR}/.env"

if [[ -f "${ENV_FILE}" ]]; then
  # shellcheck disable=SC1090
  source "${ENV_FILE}"
fi

BASE_SETTLE="${BASE_SETTLE:-90}"
SURGE_SEC="${SURGE_SEC:-120}"
TAIL_SEC="${TAIL_SEC:-120}"
TOTAL=$(( BASE_SETTLE + SURGE_SEC + TAIL_SEC ))
# Nominal spacing for SURGE_*_INDEX-only plots; metric_collector uses ~1s sleep — keep aligned unless you change collector cadence.
METRIC_SAMPLE_SEC="${METRIC_SAMPLE_SEC:-1}"
PHASE_LOG="${SCRIPT_DIR}/phase_markers.env"

ts() { printf "[%s]" "$(date +'%H:%M:%S')"; }

write_phase_header() {
  local t0 epoch0 iso0
  iso0="$(date -Iseconds)"
  epoch0="$(date -u +%s)"
  {
    echo "# Generated by run_surge_experiment.sh — wall-clock ISO timestamps (preferred for plots) + optional row indices (nominal only)"
    echo "GENERATED_AT_ISO=${iso0}"
    echo "TS_EXPERIMENT_START=${epoch0}"
    echo "BASE_SETTLE_SEC=${BASE_SETTLE}"
    echo "SURGE_SEC=${SURGE_SEC}"
    echo "TAIL_SEC=${TAIL_SEC}"
    echo "METRIC_SAMPLE_SEC=${METRIC_SAMPLE_SEC}"
    echo "SURGE_START_INDEX=$(( BASE_SETTLE / METRIC_SAMPLE_SEC ))"
    echo "SURGE_END_INDEX=$(( (BASE_SETTLE + SURGE_SEC) / METRIC_SAMPLE_SEC ))"
  } > "${PHASE_LOG}.tmp"
  mv "${PHASE_LOG}.tmp" "${PHASE_LOG}"
}

append_phase_ts() {
  local key="$1"
  local iso epoch
  iso="$(date -Iseconds)"
  epoch="$(date -u +%s)"
  printf "%s_ISO=%s\n" "${key}" "${iso}" >> "${PHASE_LOG}"
  printf "%s_EPOCH=%s\n" "${key}" "${epoch}" >> "${PHASE_LOG}"
}

cleanup() {
  echo "$(ts) Stopping all load injection..."
  make -C "${SCRIPT_DIR}" stop 2>/dev/null || true
}
trap cleanup EXIT INT TERM

echo "$(ts) === Surge Experiment ==="
echo "$(ts) Plan: base ${BASE_SETTLE}s → surge ${SURGE_SEC}s → tail ${TAIL_SEC}s (total ${TOTAL}s)"
echo "$(ts) Phase markers → ${PHASE_LOG}"
echo ""

write_phase_header

echo "$(ts) Phase 1/3: starting base load, settling for ${BASE_SETTLE}s"
append_phase_ts "BASE_LOAD_START"
make -C "${SCRIPT_DIR}" inject-base
sleep "${BASE_SETTLE}"

echo ""
echo "$(ts) Phase 2/3: injecting surge for ${SURGE_SEC}s (base continues)"
append_phase_ts "SURGE_START"
INJECT_DURATION="${SURGE_SEC}s" "${SCRIPT_DIR}/start_injection_surge.sh"
sleep "${SURGE_SEC}"

append_phase_ts "SURGE_END"
echo ""
echo "$(ts) Phase 3/3: post-surge tail ${TAIL_SEC}s (base still running)"
append_phase_ts "TAIL_START"
sleep "${TAIL_SEC}"

append_phase_ts "EXPERIMENT_END"

echo ""
echo "$(ts) Experiment complete. Cleanup will stop all processes."
